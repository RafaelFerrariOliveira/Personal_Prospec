namespace PersonalProspec.Domain.Handlers.PaginationSettings;

// Contrato com o front: serializa como { items, totalCount, pageNumber, pageSize, totalPages }.
public sealed class PageList<T>
{
    public IReadOnlyList<T> Items { get; }
    public int TotalCount { get; }
    public int PageNumber { get; }
    public int PageSize { get; }
    public int TotalPages { get; }

    public PageList()
    {
        Items = [];
    }

    public PageList(IReadOnlyList<T> items, int totalCount, int pageNumber, int pageSize)
    {
        Items = items;
        TotalCount = totalCount;
        PageNumber = pageNumber;
        PageSize = pageSize;
        TotalPages = pageSize > 0 ? (int)Math.Ceiling(totalCount / (double)pageSize) : 0;
    }
}
